const data = JSON.parse(fs.readFileSync(path.join(ROOT, "data.json"), "utf8"));
const cat = data.categories.find((c) => c.id === "anime");
const byTitle = new Map(cat.items.map((i) => [i.title, i]));

if (LIST) {
  for (const [t] of DATA) console.log(`${byTitle.has(t) ? "ok  " : "MISS"}  ${t}`);
  process.exit(0);
}

const parsed = JSON.parse(fs.readFileSync(F, "utf8"));
let y = 0, d = 0, c = 0;
const miss = [];

for (const [folder, year, director, cast] of DATA) {
  const item = byTitle.get(folder);
  if (!item) { miss.push(folder); continue; }
  const r = parsed.items[item.id];
  if (!r) { miss.push(folder); continue; }

  if (year && !r.releaseDate) { r.releaseDate = year; y++; }
  if (director && !r.director) {
    r.director = director;
    if (!Array.isArray(r.directors) || !r.directors.length) r.directors = [director];
    d++;
  }
  const hasCast = Array.isArray(r.cast) && r.cast.length > 0;
  if (cast && cast.length && !hasCast) { r.cast = cast; c++; }

  r.extra = { ...(r.extra || {}), factsSource: "بحث يدوي" };
}

if (!DRY) fs.writeFileSync(F, JSON.stringify(parsed, null, 2) + "\n");
console.log(`\nسنة: ${y} · مخرج: ${d} · أبطال: ${c} · لم يُطبّق: ${miss.length} ${DRY ? "(dry run)" : ""}`);
for (const m of miss) console.log(`  no folder: ${m}`);
