const cat = "cartoon-films";
const data = JSON.parse(fs.readFileSync(path.join(ROOT, "data.json"), "utf8"));
const byTitle = new Map(data.categories.find((c) => c.id === cat).items.map((i) => [i.title, i]));

if (LIST) {
  for (const [t] of DATA) console.log(`${byTitle.has(t) ? "ok  " : "MISS"}  ${t}`);
  process.exit(0);
}

const file = path.join(ROOT, "details", `${cat}.json`);
const parsed = JSON.parse(fs.readFileSync(file, "utf8"));
let n = 0;
const miss = [];

for (const [folder, cast] of DATA) {
  const item = byTitle.get(folder);
  if (!item) { miss.push(folder); continue; }
  const r = parsed.items[item.id];
  if (!r) { miss.push(folder); continue; }
  if (Array.isArray(r.cast) && r.cast.length) continue;
  r.cast = cast;
  n++;
}

if (!DRY) fs.writeFileSync(file, JSON.stringify(parsed, null, 2) + "\n");
console.log(`\nأبطال: ${n} · لم يُطبّق: ${miss.length} ${DRY ? "(dry run)" : ""}`);
for (const m of miss) console.log(`  no folder: ${m}`);
